"""Generate local achievement sprite offsets; metadata only, no ROM pixels."""
from pathlib import Path
import json
ROOT = Path(__file__).resolve().parents[2]
source = (ROOT / 'port/web/cards.js').read_text(encoding='utf-8')
data = json.loads(source[source.index('={') + 1:].rstrip().rstrip(';'))
source = (ROOT / 'port/web/achievements.js').read_text(encoding='utf-8')
names = source.split('const achievementArt=', 1)[1].split(';', 1)[0]
# The browser and launcher share this stable sequence of card kinds.
import ast
names = ast.literal_eval(names)
assert len(names) == 16
out = '/* Generated by gen_achievement_art.py; metadata only, no cartridge pixels. */\n'
out += 'static const unsigned sAchievementCardArt[16][3][2] = {\n'
for name in names:
    card = next(c for c in data['cards'] if data['kinds'][c[0]] == name)
    pairs = [(data['sprites'][card[5+r]][0][r], data['sprites'][card[5+r]][1][r]) for r in range(3)]
    out += '    {' + ', '.join('{0x%x, 0x%x}' % p for p in pairs) + '}, /* ' + name + ' */\n'
out += '};\n'
(ROOT / 'port/src/port_achievement_art.inc').write_text(out, encoding='utf-8')
