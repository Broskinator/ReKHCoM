"""Compile the selected transparent controller asset into the native UI palette.

Image editing/background removal is performed with imagegen. This compiler only
normalizes an RGBA asset for the software framebuffer: nearest sampling, bounded
palette, binary coverage and C arrays. No runtime decoder or external file needed.
"""
from pathlib import Path
import hashlib
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'port/assets/controller/ultimate2c-transparent.png'
OUTPUT = ROOT / 'port/src/port_controller_art.inc'
WIDTH, HEIGHT = 104, 72

image = Image.open(SOURCE).convert('RGBA')
alpha = image.getchannel('A')
if alpha.getextrema() != (0, 255):
    raise SystemExit('Expected genuine background transparency and opaque art')
image = image.crop(alpha.point(lambda value: 255 if value >= 128 else 0).getbbox())
image = image.resize((WIDTH, HEIGHT), Image.Resampling.NEAREST)
coverage = list(image.getchannel('A').get_flattened_data())
indexed = image.convert('RGB').quantize(colors=48, method=Image.Quantize.MEDIANCUT,
                                      dither=Image.Dither.NONE)
palette = indexed.getpalette()
colors = [0] + [0xFF000000 | (palette[i * 3] << 16) | (palette[i * 3 + 1] << 8) |
                palette[i * 3 + 2] for i in range(48)]
pixels = [value + 1 if opacity >= 128 else 0
          for value, opacity in zip(indexed.get_flattened_data(), coverage)]
lines = ['/* Generated by port/tools/import_controller_art.py; do not hand edit.',
         f' * Source SHA256: {hashlib.sha256(SOURCE.read_bytes()).hexdigest()} */',
         f'#define CONTROL_ART_W {WIDTH}', f'#define CONTROL_ART_H {HEIGHT}',
         'static const uint32_t sControlArtPalette[] = {']
lines.extend('    ' + ', '.join(f'0x{value:08X}u' for value in colors[i:i + 6]) + ','
             for i in range(0, len(colors), 6))
lines.extend(['};', 'static const uint8_t sControlArt[CONTROL_ART_H][CONTROL_ART_W] = {'])
lines.extend('    {' + ','.join(map(str, pixels[y * WIDTH:(y + 1) * WIDTH])) + '},'
             for y in range(HEIGHT))
lines.append('};')
OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
native = Image.new('RGBA', (WIDTH, HEIGHT))
native.putdata([((colors[index] >> 16) & 255, (colors[index] >> 8) & 255,
                 colors[index] & 255, 255 if index else 0) for index in pixels])
native.save(ROOT / 'port/assets/controller/ultimate2c-sprite.png')
print(f'{OUTPUT}: {WIDTH}x{HEIGHT}, 48 colours + transparent, {len(pixels)} bytes of indices')
