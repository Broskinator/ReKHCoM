"""Generate the official achievement set the game evaluates without an account.

Inputs (both public catalog data, no account data):
  --catalog  a launcher cache/achievements-768.dat (ids, points, titles,
             descriptions, badge names), written after browsing the catalog
  --definitions  build/ra-reference-audit/references.csv.definitions.json
             (each achievement's trigger, from audit_ra_references.py)

  --badges   a folder of the badge PNGs (<badge>.png, 64x64), e.g. a launcher's
             cache/achievement-badges

Writes port/achievements/official_set_eu.inc (C), port/web/achievement-data.js
and port/assets/achievements/badges.png: one lossless atlas of the badges, 10 per
row in set order (64x64 each), read by the game, the launcher and the web page.
RetroAchievements' own warning entries (ids from 101000001) are left out.
"""
import argparse
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WARNING_ID = 101000001


def read_catalog(path):
    data = path.read_bytes()
    if data[:8] != b'KHRACAT1':
        raise SystemExit(f'{path}: not a launcher achievement catalog')
    count = struct.unpack_from('<I', data, 8)[0]
    offset = 12
    items = []

    def text():
        nonlocal offset
        size = struct.unpack_from('<I', data, offset)[0]
        offset += 4
        value = data[offset:offset + size].decode('utf-8')
        offset += size
        return value
    for _ in range(count):
        ident, points = struct.unpack_from('<II', data, offset)
        offset += 8
        items.append({'id': ident, 'points': points, 'title': text(), 'description': text(), 'badge': text()})
    return items


def c_string(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--catalog', type=Path, required=True)
    parser.add_argument('--definitions', type=Path, default=ROOT / 'build/ra-reference-audit/references.csv.definitions.json')
    parser.add_argument('--badges', type=Path, required=True)
    args = parser.parse_args()
    catalog = [a for a in read_catalog(args.catalog) if a['id'] < WARNING_ID]
    definitions = {d['id']: d['definition'] for d in json.loads(args.definitions.read_text(encoding='utf-8'))}
    missing = [a['id'] for a in catalog if a['id'] not in definitions]
    if missing:
        raise SystemExit(f'no trigger for {missing}')
    catalog.sort(key=lambda a: a['id'])
    lines = ['/* Generated by port/tools/gen_official_set.py; do not hand edit.',
             ' * Kingdom Hearts: Chain of Memories (European cartridge) set from',
             ' * RetroAchievements (retroachievements.org), credited to its authors:',
             ' * titles, descriptions, points, badge names and triggers. */',
             f'#define KH_OFFICIAL_COUNT {len(catalog)}',
             'static const KhOfficialAchievement gKhOfficialSet[KH_OFFICIAL_COUNT] = {']
    for a in catalog:
        lines.append(f'    {{ {a["id"]}u, {a["points"]}u, {c_string(a["title"])}, {c_string(a["description"])}, '
                     f'{c_string(a["badge"])}, {c_string(definitions[a["id"]])} }},')
    lines.append('};')
    (ROOT / 'port/achievements/official_set_eu.inc').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    web = [[a['id'], a['points'], a['title'], a['description'], a['badge']] for a in catalog]
    (ROOT / 'port/web/achievement-data.js').write_text(
        '// Generated by gen_official_set.py: the official set (RetroAchievements), EU cartridge.\n'
        'window.ReKHOfficialAchievements=' + json.dumps(web, ensure_ascii=False, separators=(',', ':')) + ';\n',
        encoding='utf-8')
    from PIL import Image
    atlas = Image.new('RGB', (640, 64 * ((len(catalog) + 9) // 10)), (255, 255, 255))
    for i, a in enumerate(catalog):
        badge = Image.open(args.badges / f'{a["badge"]}.png').convert('RGBA')
        if badge.size != (64, 64):
            raise SystemExit(f'badge {a["badge"]}: {badge.size}, expected 64x64')
        atlas.paste(badge, ((i % 10) * 64, (i // 10) * 64), badge)
    out = ROOT / 'port/assets/achievements/badges.png'
    out.parent.mkdir(parents=True, exist_ok=True)
    atlas.save(out, optimize=True)
    print(f'{len(catalog)} achievements, {sum(a["points"] for a in catalog)} points, atlas {out.stat().st_size} bytes')


if __name__ == '__main__':
    main()
