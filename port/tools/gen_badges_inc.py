"""Embed the achievement badge atlas (port/assets/achievements/badges.png) in the
game and the launcher, so the badges show on every version even when the file
is missing next to the executable (development builds, console data folders).

    python port/tools/gen_badges_inc.py           # rewrite port/include/port/badges_png.inc
    python port/tools/gen_badges_inc.py --check   # exit 1 if it is out of date
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'port/assets/achievements/badges.png'
OUT = ROOT / 'port/include/port/badges_png.inc'


def render():
    data = SRC.read_bytes()
    lines = ['/* Generated by port/tools/gen_badges_inc.py from port/assets/achievements/badges.png. */']
    for i in range(0, len(data), 24):
        lines.append(','.join(str(b) for b in data[i:i + 24]) + ',')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        # a CRLF checkout (core.autocrlf) holds the same bytes
        ok = OUT.exists() and OUT.read_bytes().replace(b'\r\n', b'\n').decode('ascii') == text
        print(('up to date: ' if ok else 'OUT OF DATE: ') + str(OUT.relative_to(ROOT)))
        sys.exit(0 if ok else 1)
    OUT.write_text(text, encoding='ascii', newline='\n')
    print(f'{OUT.relative_to(ROOT)}: {SRC.stat().st_size} bytes')
