"""The HD cards' value digits, drawn with the dialogue's HD font (port/assets/fonts/KHMenu.otf) instead of Re:CoM's
italic ones (user, 22/10/2026), and embedded in the game: they are ours, so every version has them without an import.

Each digit fills the GBA digit's own place in its 8x8 sprite (the recipe's place= of port/data/hd_sprites.tsv) at x8,
condensed to that width as the HD text condenses the face to the pixel font: white for the plain value, the
cartridge's blue for a modified one, with a dark outline.

    python port/tools/gen_card_digits_inc.py           # rewrite port/include/port/hd_card_digits.inc
    python port/tools/gen_card_digits_inc.py --check   # exit 1 if it is out of date
    python port/tools/gen_card_digits_inc.py --sheet out.png
"""
import io
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / 'port/assets/fonts/KHMenu.otf'
TSV = ROOT / 'port/data/hd_sprites.tsv'
OUT = ROOT / 'port/include/port/hd_card_digits.inc'
SCALE = 8
OUTLINE = 4
FACE = {'gCardValueDigitTiles': (255, 255, 255), 'gCardModifiedValueDigitTiles': (0x29, 0x7B, 0xFF)}


def places():
    """name -> (tiles, digit, box w, box h, place) for the digit rows of the recipe table."""
    rows = {}
    for line in TSV.read_text(encoding='utf-8').splitlines():
        if not line or line.startswith('#'):
            continue
        f = line.split('\t')
        if f[3] not in FACE:
            continue
        place = next(p[6:] for p in f[9].split(';') if p.startswith('place='))
        rows[f[0]] = (f[3], int(f[0].rsplit('_', 1)[1]), int(f[6]), int(f[7]), [int(v) for v in place.split(',')])
    return rows


def digit(font, d, tiles, w, h, place):
    ref = font.getbbox('0')
    bb = font.getbbox(str(d))
    ink = Image.new('L', (bb[2] - bb[0] + 8, ref[3] - ref[1] + 8), 0)
    ImageDraw.Draw(ink).text((4 - bb[0], 4 - ref[1]), str(d), font=font, fill=255)
    ink = ink.crop(ink.getbbox())
    x0, y0, x1, y1 = (v * SCALE for v in place)
    gh = y1 - y0 - 2 * OUTLINE
    gw = round((x1 - x0 - 2 * OUTLINE) * (0.6 if d == 1 else 1.0))
    ink = ink.resize((gw, gh), Image.LANCZOS)
    mask = Image.new('L', (w * SCALE, h * SCALE), 0)
    mask.paste(ink, ((x0 + x1 - gw) // 2, y0 + OUTLINE))
    out = Image.new('RGBA', mask.size, (0, 0, 0, 0))
    out.paste((16, 16, 24, 255), (0, 0), mask.filter(ImageFilter.MaxFilter(OUTLINE * 2 + 1)))
    out.paste(FACE[tiles] + (255,), (0, 0), mask)
    return out


def pictures():
    font = ImageFont.truetype(str(FONT), 400)
    rows = places()
    # one place per set (its 0's): the recipe narrows Re:CoM's 1, which here is narrowed by digit()
    zero = {tiles: place for tiles, d, w, h, place in rows.values() if d == 0}
    return {name: digit(font, d, tiles, w, h, zero[tiles]) for name, (tiles, d, w, h, place) in sorted(rows.items())}


def render():
    lines = ['/* Generated by port/tools/gen_card_digits_inc.py from port/assets/fonts/KHMenu.otf: the HD cards\' value',
             '   digits (PNG), by their name in port/data/hd_sprites.tsv. */']
    names = []
    for i, (name, img) in enumerate(pictures().items()):
        buf = io.BytesIO()
        img.save(buf, 'PNG', optimize=True)
        data = buf.getvalue()
        lines.append(f'static const unsigned char kCardDigit{i}[] = {{')
        for k in range(0, len(data), 24):
            lines.append(','.join(str(b) for b in data[k:k + 24]) + ',')
        lines.append('};')
        names.append(f'    {{ "{name}", kCardDigit{i}, sizeof(kCardDigit{i}) }},')
    lines.append('static const struct { const char* name; const unsigned char* png; int size; } kCardDigits[] = {')
    lines += names
    lines.append('};')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    if '--sheet' in sys.argv:
        pics = list(pictures().values())
        sheet = Image.new('RGBA', (64 * len(pics), 64), (40, 40, 40, 255))
        for i, p in enumerate(pics):
            sheet.alpha_composite(p, (i * 64, 0))
        sheet.save(sys.argv[sys.argv.index('--sheet') + 1])
        sys.exit(0)
    text = render()
    if '--check' in sys.argv:
        ok = OUT.exists() and OUT.read_bytes().replace(b'\r\n', b'\n').decode('ascii') == text
        print(('up to date: ' if ok else 'OUT OF DATE: ') + str(OUT.relative_to(ROOT)))
        sys.exit(0 if ok else 1)
    OUT.write_text(text, encoding='ascii', newline='\n')
    print(f'{OUT.relative_to(ROOT)}: {text.count("kCardDigit") // 3} digits')
